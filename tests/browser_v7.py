"""Real mobile Chromium checks. Run against a running isolated v7 server."""
import os,sys,json
from pathlib import Path
from datetime import date,timedelta
from playwright.sync_api import sync_playwright, expect
BASE=os.environ.get('TEST_BASE_URL','http://127.0.0.1:8177')
with sync_playwright() as pw:
    browser=pw.chromium.launch(headless=True,args=['--no-sandbox'])
    ctx=browser.new_context(viewport={'width':390,'height':844},device_scale_factor=1,permissions=['clipboard-read','clipboard-write'])
    # No external image or font dependency; keep tests deterministic.
    ctx.route('https://images.unsplash.com/**',lambda r:r.abort())
    ctx.route('**/api/fx',lambda r:r.fulfill(json={'rates':{'PLN':1,'EUR':.23,'USD':.25}}))
    errors=[];page=ctx.new_page();page.on('pageerror',lambda e:errors.append(str(e)))
    for niche in ['barber','beauty','auto','detailing']:
        page.goto(BASE+'/?demo=1&niche='+niche)
        expect(page.locator('#services-grid .svc')).to_have_count(5)
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth+1'),niche+' overflow'
        page.locator('[data-quiz-open]').click()
        page.locator('[data-answer="1"]').click();page.locator('[data-answer="2"]').click()
        if niche in ['auto','detailing']:page.locator('.quiz-addon input[value=ozone]').check()
        page.locator('#quiz-calculate').click();expect(page.locator('#quiz-book')).to_be_visible()
        expect(page.locator('.quote-total')).to_contain_text('PLN')
        # Translation changes in an open multi-step modal.
        page.evaluate("applyLang('pl')")
        expect(page.locator('#quiz-book')).to_have_text('Zarezerwuj ten pakiet')
        page.locator('#quiz-book').click();expect(page.locator('#package-summary')).to_be_visible()
        page.locator('#name').fill('Mobile Demo');page.locator('#phone').fill('+48500100200')
        page.locator('#date').fill((date.today()+timedelta(days=3)).isoformat());page.locator('#date').dispatch_event('change')
        expect(page.locator('.slot').first).to_be_visible();page.locator('.slot').first.click();page.locator('#submit-btn').click()
        expect(page.locator('#ok-modal')).to_have_class('modal-back on')
        page.locator('#ok-modal [data-my-close]').click();page.evaluate("applyLang('en')")
        print('PASS mobile quiz, optional addons, pricing, Polish, demo booking:',niche)
    page.goto(BASE+'/?demo=1&niche=auto');page.locator('.fab').click()
    page.locator('[data-pitch=quiz]').click();expect(page.locator('.growth-overlay')).to_be_visible();page.keyboard.press('Escape')
    page.locator('.fab').click();page.locator('[data-pitch=report]').click();expect(page.locator('.growth-overlay')).to_contain_text('fictional data');page.keyboard.press('Escape')
    print('PASS one-tap quiz and sandbox report shortcuts')
    page.goto(BASE+'/feedback/demo');page.locator('[data-rating="2"]').click()
    page.locator('#fb-comment').fill('We waited 25 minutes');page.locator('#fb-contact').fill('+48500100200')
    page.locator('#fb-submit').click();expect(page.locator('.feedback-success')).to_contain_text('no data saved')
    page.goto(BASE+'/feedback/demo');page.locator('[data-rating="5"]').click()
    page.evaluate("applyLang('pl')");expect(page.locator('#fb-copy')).to_contain_text('Skopiuj')
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth+1')
    print('PASS private feedback sandbox, own review editor, language switching, mobile fit')
    page.goto(BASE+'/admin');page.locator('#login-pw').fill('admin123');page.locator('#login-btn').click()
    expect(page.locator('#main-panel')).to_be_visible()
    page.evaluate("applyLang('en')");page.locator('#growth-seed').click()
    expect(page.locator('#growth-toast')).to_contain_text('Sample')
    page.locator('[data-show=feedback]').click();expect(page.locator('.feedback-item')).to_have_count(4)
    page.locator('[data-show=settings]').click();expect(page.locator('#growth-settings')).to_be_visible()
    page.locator('#g-google').fill('https://g.page/r/salon-review/review');page.locator('#g-time').fill('21:30');page.locator('#growth-save').click()
    expect(page.locator('#growth-toast')).to_contain_text('saved')
    page.locator('[data-show=outreach]').click();page.locator('#pv-name').fill('Luna Beauty Warsaw');page.locator('#pv-logo').fill('')
    expect(page.locator('#pv-copy')).to_be_enabled();link=page.locator('#pv-url').input_value();assert '/d/' in link
    page.goto(link);expect(page.locator('#brand-name')).to_have_text('Luna Beauty Warsaw');expect(page.locator('#brand-logo')).to_be_hidden()
    print('PASS CRM sample feedback, settings save, live no-logo short link')
    page.goto(BASE+'/');expect(page.locator('#services-grid .svc').first).to_be_visible()
    page.locator('[data-quiz-open]').click();page.locator('[data-answer="0"]').click();page.locator('[data-answer="1"]').click()
    page.locator('#quiz-calculate').click();expect(page.locator('#quiz-book')).to_be_visible()
    page.locator('#quiz-book').click();page.locator('#name').fill('Real Browser Tester');page.locator('#phone').fill('+48500888777')
    page.locator('#date').fill((date.today()+timedelta(days=4)).isoformat());page.locator('#date').dispatch_event('change')
    expect(page.locator('.slot').first).to_be_visible();page.locator('.slot').first.click();page.locator('#submit-btn').click()
    expect(page.locator('#ok-modal')).to_have_class('modal-back on')
    bookings=ctx.request.get(BASE+'/api/admin/bookings').json()
    real=next(b for b in bookings if b['client_name']=='Real Browser Tester')
    assert 'Package:' in real['notes'] and real['duration_min']>45
    assert ctx.request.patch(BASE+'/api/admin/bookings/'+str(real['id']),data={'status':'Completed'}).ok
    page.goto(BASE+'/admin');expect(page.locator('#main-panel')).to_be_visible();page.locator('[data-show=bookings]').click()
    expect(page.locator('[data-review="'+str(real['id'])+'"]').first).to_be_visible()
    page.locator('[data-review="'+str(real['id'])+'"]').first.click()
    expect(page.locator('.review-url')).to_be_visible();review_url=page.locator('.review-url').input_value()
    page.goto(review_url);page.locator('[data-rating="5"]').click();expect(page.locator('#fb-google-link')).to_be_visible()
    page.locator('[data-rating="2"]').click();expect(page.locator('#fb-google-link')).to_be_visible()
    page.locator('#fb-comment').fill('Waited too long, please call back.');page.locator('#fb-submit').click()
    expect(page.locator('.feedback-success')).to_contain_text('Received')
    print('PASS real package booking, completed-booking review action, signed link and private feedback')
    page.goto(BASE+'/?demo=1&niche=detailing');expect(page.locator('#services-grid .svc')).to_have_count(5)
    page.screenshot(path=os.environ.get('TEST_SCREENSHOT',str(Path(__file__).resolve().parent/'mobile-preview.png')),full_page=True)
    assert not errors,errors
    print('PASS no uncaught JavaScript errors; mobile screenshot saved')
    browser.close()
